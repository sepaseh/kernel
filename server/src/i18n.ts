export type Translator = (
  key: TranslationKey,
  values?: Record<string, string | number>,
) => string;

const instance = createInstance();
void instance.init({
  fallbackLng: "en",
  initAsync: false,
  interpolation: { escapeValue: false },
  resources: {
    ...Object.fromEntries(
      Object.entries(additionalLocales).map(([language, translation]) => [
        language,
        { translation },
      ]),
    ),
    en: { translation: en },
    fa: { translation: fa },
  },
});

export const getTranslator = (language: string): Translator => {
  const fixed = instance.getFixedT(language);
  return (key, values) => fixed(key, values);
};
